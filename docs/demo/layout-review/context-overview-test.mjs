import assert from 'node:assert/strict';
import { contextOverview } from './context-overview-model.mjs';
import { useOfficialContext } from './official-reader.mjs';
const pressure = { projectedTokens: 280000, pressureTokens: 279000, contextWindow: 1048576 };
const breakdown = { systemTokens: 1000, toolsTokens: 10000, messageTokens: 200000 };
const composition = { system: 1000, tools: 10000, user: 2000, inject: 4000, skill: 0, assistant: 140000, tool: 60000 };
const result = contextOverview(pressure, breakdown, composition);
assert.equal(result.used, pressure.projectedTokens);
assert.equal(result.estimatedTotal, 217000, 'composition estimates must not be scaled into fake exact token counts');
assert.equal(result.categories.some(c => c.key === 'skill'), false, 'zero contributions stay out of the legend');
assert.ok(Math.abs(result.categories.reduce((n, c) => n + c.share, 0) - 100) < 1e-9);
assert.equal(result.percent, 280000 / 1048576 * 100);
const fallback = contextOverview(pressure, breakdown);
assert.deepEqual(fallback.categories.map(c => c.key), ['system', 'tools', 'messages']);
assert.equal(contextOverview(undefined, breakdown).used, null);
assert.equal(contextOverview({ contextWindow: 0 }, breakdown).percent, null);
assert.equal(contextOverview({ projectedTokens: 0, pressureTokens: 900, contextWindow: 1000 }, breakdown).used, 0);
const excess = contextOverview({ projectedTokens: 1100, contextWindow: 1000 }, breakdown);
assert.equal(excess.fill, 100); assert.ok(Math.abs(excess.percent - 110) < 1e-9);
const sources = { contextPressure: pressure, contextBreakdown: breakdown, contextTimeline: { current: composition, model: 'recorded-model' } };
const read = useOfficialContext(key => sources[key]);
assert.equal(read.pressure, pressure); assert.equal(read.breakdown, breakdown); assert.equal(read.composition, composition);
assert.equal(useOfficialContext(() => undefined).pressure, undefined);
console.log('PASS official context references, optional detailed composition, independent estimates, zero/missing/over-capacity states');
