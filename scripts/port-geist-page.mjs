// Turn the built Geist study page into the plugin's served 路径 page.
//
// Source of truth is the demo: docs/demo/layout-review builds .dsh/layout-review/geist.html.
// This script only splits that page into the plugin's two runtime assets and copies the
// pure model modules the Host half needs. Re-run it after changing the demo, then repack.
//
//   node scripts/build-geist-demo.mjs
//   node scripts/port-geist-page.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const demo = resolve('docs/demo/layout-review');
const out = resolve('plugin/analysis-view/lib/trace');
const page = readFileSync(resolve('.dsh/layout-review/geist.html'), 'utf8');

const DATA_OPEN = '<script id="trace-data" type="application/json">';
const at = page.indexOf(DATA_OPEN);
const dataClose = page.indexOf('</script>', at);
if (at < 0 || dataClose < 0) throw new Error('Geist page has no trace-data payload');
const head = page.slice(0, at);
const afterData = dataClose + '</script>'.length;

const scriptOpen = page.indexOf('>', page.indexOf('<script>', afterData)) + 1;
const scriptClose = page.lastIndexOf('</script>');
if (scriptOpen < 0 || scriptClose < scriptOpen) throw new Error('Geist page has no renderer script');
const original = page.slice(scriptOpen, scriptClose);
const renderer = original.replace(/^\r?\n/, '');

const WRAP_HEAD = "(() => {\n  'use strict';\n  const data = JSON.parse(document.getElementById('trace-data').textContent);";
if (!renderer.startsWith(WRAP_HEAD)) throw new Error('Renderer boot seam changed');
const WRAP_TAIL = '})();';
if (!renderer.trimEnd().endsWith(WRAP_TAIL)) throw new Error('Renderer close seam changed');
const body = renderer.trimEnd().slice(0, renderer.trimEnd().length - WRAP_TAIL.length);
const boot = body.replace(WRAP_HEAD, "window.__geistBoot = () => {\n  'use strict';\n  const data = window.__geistPayload;") + '};\n';

const GENERATED = '/* Generated by scripts/port-geist-page.mjs from the /geist demo. Edit docs/demo/layout-review and re-run; do not edit this file. */\n';

// The shell boots its trunk immediately and accepts later official/layer patches.
let shell = head
  .replace(/<title>[^<]*<\/title>/, '<title>执行路径</title>')
  .replaceAll('/fonts/', '/analysis-view/trace/fonts/')
  .replace('<a href="/versions/files-v1" target="_blank" rel="noopener" class="geist-previous" title="打开已固定的文件层版本">上一版 ↗</a>', '');
if (shell.includes('/versions/files-v1')) throw new Error('Previous-version link seam changed');

const BRIDGE = '<script>\n' + readFileSync(resolve(demo, 'trace-bridge.js'), 'utf8') + '\n</script>\n</body>\n</html>\n';

const template = shell + DATA_OPEN + '/*__TRACE_DATA__*/</script>\n<script>/*__TRACE_RENDERER__*/</script>\n' + BRIDGE;
mkdirSync(out, { recursive: true });
writeFileSync(resolve(out, 'page.html'), template);
writeFileSync(resolve(out, 'page.js'), GENERATED + boot);

const MODELS = ['step-insight.mjs', 'tool-operation-model.mjs', 'tool-result-model.mjs', 'context-model.mjs', 'context-overview-model.mjs', 'actor-model.mjs', 'branch-layout.mjs', 'meaning.mjs', 'file-model.mjs', 'diff-model.mjs', 'navigation-model.mjs'];
mkdirSync(resolve(out, 'models'), { recursive: true });
for (const name of MODELS) writeFileSync(resolve(out, 'models', name), GENERATED + readFileSync(resolve(demo, name), 'utf8'));

const FONTS = [['Geist-Variable.woff2'], ['GeistMono-Variable.woff2'], ['LICENSE.txt']];
mkdirSync(resolve(out, 'fonts'), { recursive: true });
for (const [name] of FONTS) copyFileSync(resolve(demo, 'fonts', name), resolve(out, 'fonts', name));

// Reproduce the served page from the assets so the split cannot silently lose a byte.
const rebuilt = template
  .replace(/\/\*__TRACE_DATA__\*\/|\/\*__TRACE_RENDERER__\*\//g,
    token => (token === '/*__TRACE_DATA__*/' ? JSON.stringify({ probe: true }) : original))
  .replace(BRIDGE, '</body>\n</html>\n');
const expected = page
  .replace(/<title>[^<]*<\/title>/, '<title>执行路径</title>')
  .replaceAll('/fonts/', '/analysis-view/trace/fonts/')
  .replace('<a href="/versions/files-v1" target="_blank" rel="noopener" class="geist-previous" title="打开已固定的文件层版本">上一版 ↗</a>', '')
  .replace(/<script id="trace-data" type="application\/json">[\s\S]*?<\/script>/, '<script id="trace-data" type="application/json">{"probe":true}</script>');
if (rebuilt !== expected) throw new Error('Rebuilt page differs from the demo page beyond the expected edits');

console.log(JSON.stringify({ template: template.length, renderer: boot.length, models: MODELS.length }));
