// Package the same native-event projection used by the path view. No metric fork.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const out = 'plugin/trajectory-tools/lib/inspect-models';
mkdirSync(out, { recursive: true });
for (const [source, name] of [
  ['plugin/analysis-view/lib/trace-build.js', 'session.js'],
  ['docs/demo/layout-review/tool-operation-model.mjs', 'operations.mjs'],
]) {
  const expected = '// Generated by scripts/sync-inspect-models.mjs; edit ' + source + '.\n' + readFileSync(source, 'utf8');
  if (process.argv.includes('--check')) {
    if (readFileSync(out + '/' + name, 'utf8') !== expected) throw Error('Inspection model drift: ' + name);
  } else writeFileSync(out + '/' + name, expected);
}
